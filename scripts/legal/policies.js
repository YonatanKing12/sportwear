  function hebrewDate(date) {
    return date.getDate() + ' ' + MONTHS[date.getMonth()] + ' ' + date.getFullYear();
  }

  function esc(value) {
    return String(value)
      .replace(/&/g, '&amp;')
      .replace(/</g, '&lt;')
      .replace(/>/g, '&gt;')
      .replace(/"/g, '&quot;');
  }

  function clean(details) {
    var out = {};
    ['name', 'id', 'address', 'phone', 'whatsapp', 'email', 'hours'].forEach(function (key) {
      out[key] = String((details && details[key]) || '').trim();
    });
    out.vatExempt = Boolean(details && details.vatExempt);
    return out;
  }

  // A number written with a leading + would show its + on the wrong side in right-to-left text.
  function phone(value) {
    var safe = esc(value);
    return /^\+/.test(value) ? '⁦' + safe + '⁩' : safe;
  }

  function mail(value) {
    var safe = esc(value);
    return '<a href="mailto:' + safe + '">' + safe + '</a>';
  }

  function joinOr(parts) {
    if (parts.length < 2) return parts.join('');
    return parts.slice(0, -1).join(', ') + ' או ' + parts[parts.length - 1];
  }

