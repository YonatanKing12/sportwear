  var REQUIRED = [
    ['name', 'שם העסק'],
    ['id', 'מספר עוסק או ח״פ'],
    ['address', 'כתובת'],
    ['phone', 'טלפון'],
  ];

  function missing(details) {
    var d = clean(details);
    return REQUIRED.filter(function (pair) {
      return !d[pair[0]];
    }).map(function (pair) {
      return pair[1];
    });
  }

  function build(details, date) {
    var d = clean(details);
    var when = date || new Date();
    return {
      refund: refund(d, when),
      terms: terms(d, when),
      privacy: privacy(d, when),
      shipping: shipping(d, when),
      contact: contact(d),
    };
  }

